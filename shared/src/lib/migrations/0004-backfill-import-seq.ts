// FROZEN once applied. 0003 added `import_seq` as an identity column; for rows
// that already existed PostgreSQL assigned the values in an unspecified scan
// order. Re-number them deterministically in the best legacy import order
// available (`processed_at`, then `id`), so a rebuild replays pre-0003 history
// the same way every time. Rows inserted afterwards continue from the maximum.
// A no-op on an empty table.
export const m0004: Migration = {
  id: '0004-backfill-import-seq',
  statements: [
    `ALTER TABLE statement_files ALTER COLUMN import_seq SET GENERATED BY DEFAULT`,
    `UPDATE statement_files f SET import_seq = o.rn
  FROM (
    SELECT id, row_number() OVER (ORDER BY processed_at, id) AS rn FROM statement_files
  ) o
  WHERE f.id = o.id`,
    `SELECT setval(
  pg_get_serial_sequence('statement_files', 'import_seq'),
  COALESCE((SELECT max(import_seq) FROM statement_files), 1),
  (SELECT count(*) > 0 FROM statement_files)
)`,
    `ALTER TABLE statement_files ALTER COLUMN import_seq SET GENERATED ALWAYS`,
  ],
};
